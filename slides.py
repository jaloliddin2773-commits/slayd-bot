# HELPERS
# =========================================================

def clean_json(text: str) -> str:
    text = text.strip()

    if text.startswith("```"):
        text = re.sub(r"^```(?:json)?\s*", "", text)
        text = re.sub(r"\s*```$", "", text)

    start = text.find("{")
    end = text.rfind("}")

    if start == -1 or end == -1:
        raise ValueError("AI returned invalid JSON.")

    return text[start:end + 1]


def extract_response_text(data: dict) -> str:
    candidates = data.get("candidates", [])

    if not candidates:
        raise RuntimeError("Gemini returned no candidates.")

    candidate = candidates[0]

    content = candidate.get("content", {})
    parts = content.get("parts", [])

    texts = []

    for part in parts:
        if isinstance(part, dict) and "text" in part:
            texts.append(part["text"])

    result = "\n".join(texts).strip()

    if not result:
        raise RuntimeError("Gemini returned an empty response.")

    return result


# =========================================================
# GEMINI
# =========================================================

def ask_gemini(request_text: str) -> dict:
    if not GEMINI_API_KEY:
        raise RuntimeError(
            "GEMINI_API_KEY is missing in the server environment."
        )

    prompt = PROMPT.replace("__REQUEST__", request_text.strip())

    payload = {
        "contents": [
            {
                "role": "user",
                "parts": [
                    {
                        "text": prompt
                    }
                ]
            }
        ],
        "generationConfig": {
            "responseMimeType": "application/json",
            "temperature": 0.7,
            "maxOutputTokens": 12000
        }
    }

    errors = []

    for model in GEMINI_MODELS:
        url = GEMINI_URL.format(model=model)

        try:
            response = requests.post(
                url,
                headers={
                    "x-goog-api-key": GEMINI_API_KEY,
                    "Content-Type": "application/json",
                },
                json=payload,
                timeout=90,
            )

            if response.status_code in (429, 500, 502, 503, 504):
                errors.append(
                    f"{model}: HTTP {response.status_code}"
                )
                continue

            response.raise_for_status()

            data = response.json()

            raw_text = extract_response_text(data)
            json_text = clean_json(raw_text)

            result = json.loads(json_text)

            if not isinstance(result, dict):
                raise ValueError("AI response is not an object.")

            slides = result.get("slides")

            if not isinstance(slides, list) or not slides:
                raise ValueError("AI did not return slides.")

            result["_model"] = model

            return result

        except requests.RequestException as exc:
            errors.append(f"{model}: {exc}")

        except (ValueError, json.JSONDecodeError, RuntimeError) as exc:
            errors.append(f"{model}: {exc}")

    raise RuntimeError(
        "AI xizmatlari vaqtincha ishlamadi.\n\n"
        + "\n".join(errors)
    )


