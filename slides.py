SLIDE_W = Inches(13.333)
SLIDE_H = Inches(7.5)

BG = RGBColor(248, 249, 252)
DARK = RGBColor(22, 27, 34)
MUTED = RGBColor(92, 99, 112)
ACCENT = RGBColor(245, 102, 45)
WHITE = RGBColor(255, 255, 255)
LIGHT = RGBColor(232, 235, 240)


def add_background(slide):
    shape = slide.shapes.add_shape(
        MSO_SHAPE.RECTANGLE,
        0,
        0,
        SLIDE_W,
        SLIDE_H,
    )

    shape.fill.solid()
    shape.fill.fore_color.rgb = BG
    shape.line.fill.background()


def add_top_accent(slide):
    shape = slide.shapes.add_shape(
        MSO_SHAPE.RECTANGLE,
        0,
        0,
        Inches(0.16),
        SLIDE_H,
    )

    shape.fill.solid()
    shape.fill.fore_color.rgb = ACCENT
    shape.line.fill.background()


def add_footer(slide, number):
    line = slide.shapes.add_shape(
        MSO_SHAPE.RECTANGLE,
        Inches(0.65),
        Inches(7.05),
        Inches(12.0),
        Inches(0.01),
    )

    line.fill.solid()
    line.fill.fore_color.rgb = LIGHT
    line.line.fill.background()

    box = slide.shapes.add_textbox(
        Inches(11.8),
        Inches(7.08),
        Inches(0.7),
        Inches(0.25),
    )

    p = box.text_frame.paragraphs[0]
    p.text = str(number)
    p.font.size = Pt(9)
    p.font.color.rgb = MUTED
    p.alignment = PP_ALIGN.RIGHT


def add_text(
    slide,
    text,
    x,
    y,
    w,
    h,
    size=20,
    bold=False,
    color=DARK,
    align=PP_ALIGN.LEFT,
):
    box = slide.shapes.add_textbox(
        x,
        y,
        w,
        h,
    )

    tf = box.text_frame
    tf.clear()
    tf.word_wrap = True
    tf.vertical_anchor = MSO_ANCHOR.TOP

    p = tf.paragraphs[0]
    p.text = str(text)
    p.alignment = align

    p.font.name = "Aptos"
    p.font.size = Pt(size)
    p.font.bold = bold
    p.font.color.rgb = color

    return box


def add_title(slide, title):
    add_text(
        slide,
        title,
        Inches(0.8),
        Inches(0.55),
        Inches(11.5),
        Inches(0.8),
        size=28,
        bold=True,
        color=DARK,
    )


def add_bullet_list(slide, bullets, x, y, w, h):
    box = slide.shapes.add_textbox(x, y, w, h)

    tf = box.text_frame
    tf.clear()
    tf.word_wrap = True

    for i, bullet in enumerate(bullets[:5]):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()

        p.text = str(bullet)
        p.level = 0
        p.font.name = "Aptos"
        p.font.size = Pt(20)
        p.font.color.rgb = DARK
        p.space_after = Pt(16)

        p.text = "• " + p.text

    return box


def add_card(slide, x, y, w, h):
    card = slide.shapes.add_shape(
        MSO_SHAPE.ROUNDED_RECTANGLE,
        x,
        y,
        w,
        h,
    )

    card.fill.solid()
    card.fill.fore_color.rgb = WHITE
    card.line.color.rgb = LIGHT

    return card


def render_bullets(slide, data):
    bullets = data.get("bullets", [])

    add_bullet_list(
        slide,
        bullets,
        Inches(1.0),
        Inches(1.65),
        Inches(11.2),
        Inches(4.9),
    )


def render_two_column(slide, data):
    add_card(
        slide,
        Inches(0.75),
        Inches(1.55),
        Inches(5.85),
        Inches(4.9),
    )

    add_card(
        slide,
        Inches(6.75),
        Inches(1.55),
        Inches(5.85),
        Inches(4.9),
    )

    add_text(
        slide,
        data.get("left_title", "Left"),
        Inches(1.05),
        Inches(1.9),
        Inches(5.1),
        Inches(0.5),
        size=21,
        bold=True,
        color=ACCENT,
    )

    add_text(
        slide,
        data.get("right_title", "Right"),
        Inches(7.05),
        Inches(1.9),
        Inches(5.1),
        Inches(0.5),
        size=21,
        bold=True,
        color=ACCENT,
    )

    add_bullet_list(
        slide,
        data.get("left", []),
        Inches(1.05),
        Inches(2.55),
        Inches(5.0),
        Inches(3.3),
    )

    add_bullet_list(
        slide,
        data.get("right", []),
        Inches(7.05),
        Inches(2.55),
        Inches(5.0),
        Inches(3.3),
    )


def render_stats(slide, data):
    stats = data.get("stats", [])[:4]

    count = max(len(stats), 1)
    card_w = 2.7
    gap = 0.35

    total = count * card_w + (count - 1) * gap
    start_x = (13.333 - total) / 2

    for i, stat in enumerate(stats):
        x = Inches(start_x + i * (card_w + gap))

        add_card(
            slide,
            x,
            Inches(2.0),
            Inches(card_w),
            Inches(3.4),
        )

        add_text(
            slide,
            stat.get("value", ""),
            x + Inches(0.2),
            Inches(2.55),
            Inches(card_w - 0.4),
            Inches(0.9),
            size=32,
            bold=True,
            color=ACCENT,
            align=PP_ALIGN.CENTER,
        )

        add_text(
            slide,
            stat.get("label", ""),
            x + Inches(0.2),
            Inches(3.55),
            Inches(card_w - 0.4),
            Inches(1.1),
            size=16,
            color=MUTED,
            align=PP_ALIGN.CENTER,
        )


def render_quote(slide, data):
    quote = data.get("quote", "")
    source = data.get("source", "")

    add_card(
        slide,
        Inches(1.2),
        Inches(1.65),
        Inches(10.9),
        Inches(4.6),
    )

    add_text(
        slide,
        "“",
        Inches(1.7),
        Inches(2.0),
        Inches(1.0),
        Inches(1.0),
        size=55,
        bold=True,
        color=ACCENT,
    )

    add_text(
        slide,
        quote,
        Inches(2.0),
        Inches(2.45),
        Inches(9.3),
        Inches(2.0),
        size=26,
        bold=True,
        color=DARK,
        align=PP_ALIGN.CENTER,
    )

    if source:
        add_text(
            slide,
            source,
            Inches(2.0),
            Inches(4.85),
            Inches(9.3),
            Inches(0.5),
            size=15,
            color=MUTED,
            align=PP_ALIGN.CENTER,
        )


def render_content_slide(slide, data, number):
    add_background(slide)
    add_top_accent(slide)
    add_title(slide, data.get("title", "Untitled"))

    layout = data.get("layout", "bullets")

    if layout == "two_column":
        render_two_column(slide, data)

    elif layout == "stats":
        render_stats(slide, data)

    elif layout == "quote":
        render_quote(slide, data)

    else:
        render_bullets(slide, data)

    add_footer(slide, number)


