def build_pptx(presentation_data: dict, output_path: str) -> str:
    prs = Presentation()

    prs.slide_width = SLIDE_W
    prs.slide_height = SLIDE_H

    # Remove default slide if one exists.
    while len(prs.slides):
        r_id = prs.slides._sldIdLst[0].rId
        prs.part.drop_rel(r_id)
        del prs.slides._sldIdLst[0]

    title = presentation_data.get("title", "Presentation")
    subtitle = presentation_data.get(
        "subtitle",
        "AI-generated presentation"
    )

    # -----------------------------------------------------
    # TITLE SLIDE
    # -----------------------------------------------------

    slide = prs.slides.add_slide(prs.slide_layouts[6])

    add_background(slide)

    accent = slide.shapes.add_shape(
        MSO_SHAPE.RECTANGLE,
        0,
        0,
        Inches(0.22),
        SLIDE_H,
    )

    accent.fill.solid()
    accent.fill.fore_color.rgb = ACCENT
    accent.line.fill.background()

    add_text(
        slide,
        title,
        Inches(1.05),
        Inches(2.05),
        Inches(10.8),
        Inches(1.6),
        size=38,
        bold=True,
        color=DARK,
    )

    add_text(
        slide,
        subtitle,
        Inches(1.08),
        Inches(3.75),
        Inches(9.8),
        Inches(1.0),
        size=20,
        color=MUTED,
    )

    # Decorative block
    block = slide.shapes.add_shape(
        MSO_SHAPE.ROUNDED_RECTANGLE,
        Inches(10.75),
        Inches(5.3),
        Inches(1.45),
        Inches(0.7),
    )

    block.fill.solid()
    block.fill.fore_color.rgb = ACCENT
    block.line.fill.background()

    add_text(
        slide,
        "AI",
        Inches(10.75),
        Inches(5.43),
        Inches(1.45),
        Inches(0.35),
        size=18,
        bold=True,
        color=WHITE,
        align=PP_ALIGN.CENTER,
    )

    # -----------------------------------------------------
    # CONTENT SLIDES
    # -----------------------------------------------------

    slides = presentation_data.get("slides", [])

    for index, slide_data in enumerate(slides, start=2):
        slide = prs.slides.add_slide(prs.slide_layouts[6])

        if not isinstance(slide_data, dict):
            continue

        render_content_slide(
            slide,
            slide_data,
            index,
        )

    output = Path(output_path)
    output.parent.mkdir(parents=True, exist_ok=True)

    prs.save(str(output))

    return str(output)
